"""
OpenAI-image counterpart to generate_affordance_edits.py: same objects, same 8-affordance vocabulary,
same exact prompt template (imported, not re-typed, so the two providers' outputs are directly
comparable on identical input) -- but routed through OpenRouter instead of hitting OpenAI's API
directly, since this project's own OpenAI org hit its spend limit mid-run.

Originally this called OpenAI's Responses API with an `image_generation` tool (an agentic model
calling a separate image model as a tool). OpenRouter doesn't proxy that tool-calling mechanism --
it exposes image generation/editing through its own dedicated Image API instead
(POST https://openrouter.ai/api/v1/images), which takes the prompt and reference images directly, no
orchestrating "agent" model in between. That's a genuine simplification, not a workaround: one HTTP
call per edit, via plain `requests` (not the openai SDK, which doesn't model this endpoint's shape).
Editing (not just text-to-image) is done via `input_references`: the source image as a base64 data
URI, same as the original Responses-API version sent it. Model is openai/gpt-image-2 by default --
OpenRouter doesn't yet list OpenAI's newer gpt-image-2.5; override with OPENROUTER_IMAGE_MODEL if it
shows up there later, or to try a different provider's model.

Also judges every image with a cheap model -- gpt-4o-mini, the "cheap VLM" this project's own
experiments/run_generation.py already names in its model roster -- rather than a separate judging
script, since this project already has too many single-purpose scripts. The judge checks the same two
things this conversation kept finding by hand: (1) is the edit still recognizably a deformation of the
SAME object, not a generic real-world tool wearing its colors, and (2) does it plausibly suggest the
target affordance. On FAIL, the judge also writes a short, specific instruction for what to change,
which gets appended to the prompt for a retry -- up to MAX_GEN_ATTEMPTS (3) generate+judge rounds per
(object, affordance) pair, each one seeing the previous round's fix. A pair stops retrying once the
judge says PASS, or once all 3 attempts are used (the last attempt's image is kept either way, with
the full attempt history in manifest.json for a pair, under "attempts"). The judge goes through
OpenRouter too (openai/gpt-4o-mini), via the openai SDK pointed at OpenRouter's OpenAI-compatible
chat/completions endpoint -- that part of the API shape IS a drop-in match, unlike the image endpoint.
(The actual NVRD dataset's own generation pipeline isn't in this repo to mirror -- confirmed by
cloning github.com/AdaDTur/NVRD, which is the same public analysis-only release already checked out
locally; its own 19K images are downloaded pre-built from HuggingFace, not generated by code here.)

No manual environment setup needed -- just:
    python3 generate_affordance_edits_openai.py [object ...]
Same self-bootstrap as generate_affordance_edits.py: re-execs under ./venv and auto-loads ./.env for
OPENROUTER_API_KEY (and GEMINI_API_KEY, unused here) before any third-party import.

Every pair that exhausts all MAX_GEN_ATTEMPTS rounds and is still FAIL gets a line appended to
json/affordance_edits_openai/failures.log (timestamp, object/affordance, reasoning) -- a plain,
greppable record alongside the full per-attempt detail already kept in manifest.json.

Usage:
    python3 generate_affordance_edits_openai.py [object ...]  # default: first 5 objects (OBJECT_LIMIT)
    OBJECT_LIMIT=10 python3 generate_affordance_edits_openai.py        # all 10 local novel objects
    AFFORDANCE_LIMIT=5 python3 generate_affordance_edits_openai.py shape_16
    NO_JUDGE=1 python3 generate_affordance_edits_openai.py             # single-shot generation, no judge/retries
Pairs already at a final PASS are skipped automatically; pairs that used all 3 attempts and are still
FAIL are also skipped on a plain rerun (nothing left to try with this mechanism) -- pass --retry-failed
to give just those another full 3-attempt run (e.g. after a judge/parser fix), or --rejudge to force
every requested pair through the full pipeline again regardless of status, PASS included.
"""
import os
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
_VENV_DIR = os.path.join(HERE, "venv")
# See generate_affordance_edits.py for why this checks sys.prefix rather than sys.executable.
if os.path.isdir(_VENV_DIR) and os.path.realpath(sys.prefix) != os.path.realpath(_VENV_DIR):
    _venv_py = os.path.join(_VENV_DIR, "bin", "python3")
    os.environ["PYTHONUNBUFFERED"] = "1"
    os.execv(_venv_py, [_venv_py] + sys.argv)

import json
import time
import base64
import re
from datetime import datetime, timezone

import requests

from generate_affordance_edits import (  # noqa: E402 -- reuse, don't re-type, so prompts match exactly
    AFFORDANCE_VOCAB, NOVEL_OBJECTS, OBJECT_LIMIT, PROMPT_TEMPLATE, resolve_image_path,
)

OUT_DIR = os.path.join(HERE, "figures", "affordance_edits_openai")
JSON_DIR = os.path.join(HERE, "json", "affordance_edits_openai")
FAILURES_LOG = os.path.join(JSON_DIR, "failures.log")
os.makedirs(OUT_DIR, exist_ok=True)
os.makedirs(JSON_DIR, exist_ok=True)


def log_failure(obj: str, affordance: str, reasoning: str, n_attempts: int) -> None:
    """Appended to whenever a pair uses all MAX_GEN_ATTEMPTS rounds and is still FAIL -- a plain,
    human-readable record alongside the full detail already kept in manifest.json."""
    with open(FAILURES_LOG, "a") as f:
        f.write(f"{datetime.now(timezone.utc).isoformat()}  {obj}/{affordance}  "
                f"(exhausted {n_attempts} attempts)  final reason: {reasoning}\n")

OPENROUTER_BASE_URL = "https://openrouter.ai/api/v1"
OPENROUTER_IMAGES_URL = f"{OPENROUTER_BASE_URL}/images"
IMAGE_MODEL = os.environ.get("OPENROUTER_IMAGE_MODEL", "openai/gpt-image-2")
ASPECT_RATIO = "1:1"  # matches the NVRD renders' native square resolution
QUALITY = os.environ.get("OPENAI_IMAGE_QUALITY", "high")
# input_fidelity (the magnitude-control lever for gpt-image-1/1.5 on OpenAI's own API) isn't in this
# endpoint's supported_parameters list at all, so it's not attempted here either way. The precision-
# editing-via-named-preservation approach PROMPT_TEMPLATE already uses (see generate_affordance_edits.py)
# is the portable fallback that doesn't depend on a provider-specific parameter existing.
MAX_RETRIES = 3
RETRY_BACKOFF_S = 10
REQUEST_DELAY_S = 2

# gpt-4o-mini was the original "cheap VLM" default, but a direct comparison on shape_1 (same 8
# images, both judges) showed it miscalling 2 of 3 failures outright (a visible blade read as "lacks
# a sharp edge"; a same-design threaded re-edit read as "a different product") -- real judge error, not
# noise. gpt-6-astra got both right and gave a more specific, accurate critique on the one genuine
# failure. ~9x the cost per call in practice (~$0.0045 vs ~$0.0005, measured), still cents per object
# at this vocabulary size, so the accuracy gain is worth the switch.
JUDGE_MODEL = os.environ.get("OPENAI_JUDGE_MODEL", "openai/gpt-6-astra")
MAX_GEN_ATTEMPTS = 3  # generate+judge rounds per pair; the judge's fix feeds into the next round's prompt
JUDGE_PROMPT = (
    "You are reviewing an AI-generated image edit for a research dataset on object affordances. These "
    "images will be shown to human raters to collect ground-truth affordance-agreement judgments, so "
    "what matters most is whether an ORDINARY PERSON, glancing at the edited image alone, would agree "
    "it affords \"{affordance}\" ({gloss}) -- and would still describe it as the same kind of object "
    "(same materials/colors/design family), not a mandate that its silhouette barely changed.\n\n"
    "The first image is the ORIGINAL object. The second image is an EDITED version of it, where the "
    "goal was a MODERATE reshape -- enough change that the affordance is unmistakable, but still "
    "obviously the same product line (same materials, colors, general design), not a different object "
    "and not a generic real-world tool.\n\n"
    "Answer two questions about the EDITED image:\n"
    "1. Would an ordinary person still call it the same kind of object as the original (same materials/"
    "colors/design family) -- NOT a generic, instantly-recognizable everyday object (e.g. scissors, a "
    "hammer, a screw, a door handle) that merely borrows its colors? (A substantially changed "
    "silhouette is FINE as long as it still reads as the same abstract design, not a real-world tool.)\n"
    "2. Would an ordinary person, looking only at the edited image, agree it affords \"{affordance}\" "
    "({gloss})?\n\n"
    "Respond with EXACTLY these lines:\n"
    "Line 1: PASS if the answer to both questions is yes, otherwise FAIL.\n"
    "Line 2: one short sentence explaining why.\n"
    "Line 3 (ONLY if FAIL): one short, CONCRETE instruction to append to the image-editing prompt that "
    "would fix exactly this problem on a retry -- name the specific part/feature to change or leave "
    "alone (e.g. \"keep the three side limbs exactly as they are; only reshape the tip of the top "
    "limb\"), not a vague intensity adjective like \"smaller\" or \"more moderate\" on its own, since "
    "that alone has not been enough to change the result on past retries. If earlier attempts are "
    "listed below and one of them already overcorrected in some direction, say which specific part to "
    "pull back, not just \"do less\". Omit line 3 if PASS."
)
JUDGE_HISTORY_HEADER = (
    "\n\nEarlier attempts on this SAME (object, affordance) pair, for calibration -- do not just repeat "
    "or intensify a direction that already overcorrected:\n"
)

_LIMIT = os.environ.get("AFFORDANCE_LIMIT")
if _LIMIT:
    AFFORDANCE_VOCAB = dict(list(AFFORDANCE_VOCAB.items())[: int(_LIMIT)])


def edit_image(api_key: str, image_path: str, prompt: str):
    """Returns (png_bytes | None, error | None). Sends the source image inline as a base64 data URI
    via OpenRouter's dedicated Image API (input_references), not the openai SDK -- this endpoint's
    request/response shape (input_references, b64_json + media_type) isn't what that SDK models.
    Takes the exact prompt to use (not affordance/gloss) so a retry can pass one with the judge's fix
    appended."""
    with open(image_path, "rb") as f:
        src_b64 = base64.b64encode(f.read()).decode("ascii")

    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://github.com/AdaDTur/NVRD",  # OpenRouter's recommended attribution headers
        "X-Title": "NVRD affordance-centric edits",
    }
    payload = {
        "model": IMAGE_MODEL,
        "prompt": prompt,
        "quality": QUALITY,
        "aspect_ratio": ASPECT_RATIO,
        "input_references": [
            {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{src_b64}"}},
        ],
    }

    last_err = None
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            resp = requests.post(OPENROUTER_IMAGES_URL, headers=headers, json=payload, timeout=180)
            if resp.status_code != 200:
                last_err = f"HTTP {resp.status_code}: {resp.text[:500]}"
                print(f"    attempt {attempt}/{MAX_RETRIES} failed: {last_err}")
                if attempt < MAX_RETRIES:
                    time.sleep(RETRY_BACKOFF_S * attempt)
                continue
            data = resp.json()
            items = data.get("data") or []
            if not items or not items[0].get("b64_json"):
                last_err = f"no b64_json in response (keys: {list(data.keys())})"
                continue
            return base64.b64decode(items[0]["b64_json"]), None
        except Exception as e:  # noqa: BLE001 -- surfaced to caller, not swallowed
            last_err = str(e)
            print(f"    attempt {attempt}/{MAX_RETRIES} failed: {last_err}")
            if attempt < MAX_RETRIES:
                time.sleep(RETRY_BACKOFF_S * attempt)
    return None, last_err


def encode_image(path: str) -> str:
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")


_LINE_PREFIX_RE = re.compile(r"^(line\s*\d+\s*[:.)-]\s*)", re.IGNORECASE)


def _strip_line_prefix(line: str) -> str:
    """gpt-4o-mini sometimes echoes the literal 'Line 1:' / 'Line 2:' labels from the prompt instead
    of just the content, despite being told not to -- strip them so parsing doesn't shift by one and
    misread a PASS as a FAIL (caught happening for real in an earlier run: a line whose actual content
    clearly described a pass ("retains its original colors... clearly suggesting the affordance of
    cutting") got recorded as FAIL because it was the model's mislabeled "Line 2:" content sitting in
    the position the parser expected the verdict)."""
    return _LINE_PREFIX_RE.sub("", line).strip()


def parse_judge_response(text: str) -> tuple:
    """Returns (verdict, reasoning, prompt_fix). Robust to the model including literal 'Line N:'
    labels, blank lines, or minor reordering -- finds the line that IS "PASS" or "FAIL" (as a whole
    word, not just a prefix) rather than assuming it's always lines[0]."""
    lines = [_strip_line_prefix(l) for l in text.splitlines() if l.strip()]
    lines = [l for l in lines if l]
    verdict_idx, verdict = None, "fail"
    for i, line in enumerate(lines):
        token = line.strip().upper().rstrip(".:")
        if token in ("PASS", "FAIL") or token.startswith("PASS") or token.startswith("FAIL"):
            verdict_idx, verdict = i, ("pass" if token.startswith("PASS") else "fail")
            break
    if verdict_idx is None:  # couldn't find an explicit verdict line at all -- treat as fail, keep raw text
        return "fail", text.strip(), None
    rest = lines[verdict_idx + 1:]
    reasoning = rest[0] if rest else lines[verdict_idx]
    prompt_fix = rest[1] if verdict == "fail" and len(rest) > 1 else None
    return verdict, reasoning, prompt_fix


def judge_edit(client, source_image: str, edited_image: str, affordance: str, gloss: str, history=None):
    """Returns (verdict: 'pass'|'fail'|'error', reasoning: str, prompt_fix: str|None), using the cheap
    gpt-4o-mini model to check the edit, not the expensive model that generated it. prompt_fix is the
    judge's own suggested addition to the prompt for a retry, only set (maybe) when verdict is 'fail'.
    history: prior attempts' (verdict, reasoning, prompt_fix) for this same pair, if any -- lets the
    judge notice its own earlier fix overcorrected instead of re-diagnosing from a blank slate."""
    prompt = JUDGE_PROMPT.format(affordance=affordance, gloss=gloss)
    if history:
        prompt += JUDGE_HISTORY_HEADER + "\n".join(
            f"  Attempt {i}: {v.upper()} -- {r}" + (f" (then tried: {pf})" if pf else "")
            for i, (v, r, pf) in enumerate(history, start=1)
        )
    src_b64, edit_b64 = encode_image(source_image), encode_image(edited_image)
    last_err = None
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = client.chat.completions.create(
                model=JUDGE_MODEL,
                messages=[{
                    "role": "user",
                    "content": [
                        {"type": "text", "text": prompt},
                        {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{src_b64}"}},
                        {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{edit_b64}"}},
                    ],
                }],
                max_tokens=150,
            )
            return parse_judge_response(response.choices[0].message.content.strip())
        except Exception as e:  # noqa: BLE001
            last_err = str(e)
            print(f"    judge attempt {attempt}/{MAX_RETRIES} failed: {last_err}")
            if attempt < MAX_RETRIES:
                time.sleep(RETRY_BACKOFF_S * attempt)
    return "error", last_err, None


def generate_and_judge(
    api_key: str, judge_client, obj: str, img_path: str, affordance: str, gloss: str, out_path: str,
) -> dict:
    """Generate, judge, and -- on FAIL -- retry with the judge's own fix instruction appended to the
    prompt, up to MAX_GEN_ATTEMPTS rounds. Stops early on PASS; otherwise keeps the LAST attempt's
    image and returns the full attempt history alongside the final verdict.

    Each retry REPLACES (not accumulates) the previous round's fix -- the judge sees the full history
    instead and is told to shrink its suggestion if an earlier one already overcorrected, rather than
    piling up a growing, possibly-contradictory set of instructions across rounds."""
    extra, attempts, history = "", [], []
    verdict, reasoning = "fail", None
    for attempt_n in range(1, MAX_GEN_ATTEMPTS + 1):
        prompt = PROMPT_TEMPLATE.format(affordance=affordance, gloss=gloss) + extra
        png_bytes, err = edit_image(api_key, img_path, prompt)
        if png_bytes is None:
            attempts.append({"attempt": attempt_n, "prompt": prompt, "error": err})
            print(f"    attempt {attempt_n}/{MAX_GEN_ATTEMPTS}: generation FAILED -- {err}")
            time.sleep(REQUEST_DELAY_S)
            continue

        with open(out_path, "wb") as f:
            f.write(png_bytes)
        verdict, reasoning, prompt_fix = judge_edit(
            judge_client, img_path, out_path, affordance, gloss, history=history,
        )
        attempts.append({
            "attempt": attempt_n, "prompt": prompt, "judge_verdict": verdict,
            "judge_reasoning": reasoning, "judge_prompt_fix": prompt_fix,
        })
        history.append((verdict, reasoning, prompt_fix))
        print(f"    attempt {attempt_n}/{MAX_GEN_ATTEMPTS}: judge [{verdict.upper():5s}]: {reasoning}")
        time.sleep(REQUEST_DELAY_S)
        if verdict == "pass":
            break
        if prompt_fix:
            extra = " " + prompt_fix
            print(f"      -> retrying with guidance (replacing prior round's): {prompt_fix}")

    if verdict != "pass":
        log_failure(obj, affordance, reasoning, len(attempts))

    return {
        "status": "ok" if any("judge_verdict" in a for a in attempts) else "failed",
        "prompt": attempts[-1]["prompt"] if attempts else None,
        "judge_model": JUDGE_MODEL, "judge_verdict": verdict, "judge_reasoning": reasoning,
        "attempts": attempts, "retry_exhausted": verdict != "pass",
    }


def main():
    do_judge = not os.environ.get("NO_JUDGE")
    rejudge = "--rejudge" in sys.argv
    retry_failed = "--retry-failed" in sys.argv
    args = [a for a in sys.argv[1:] if a not in ("--rejudge", "--retry-failed")]
    objects = args if args else NOVEL_OBJECTS[:OBJECT_LIMIT]
    if not objects:
        print("No novel objects found.")
        return
    print(f"Objects ({len(objects)}): {objects}")

    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key:
        print("OPENROUTER_API_KEY is not set -- add it to .env and rerun.")
        sys.exit(1)

    from openai import OpenAI
    # Judge only -- chat/completions IS a drop-in OpenAI-compatible match on OpenRouter, unlike the
    # image endpoint edit_image() talks to directly via requests.
    judge_client = OpenAI(api_key=api_key, base_url=OPENROUTER_BASE_URL)

    manifest_path = os.path.join(JSON_DIR, "manifest.json")
    existing = []
    if os.path.isfile(manifest_path):
        with open(manifest_path) as f:
            existing = json.load(f)
    # Keyed dict IS the manifest from here on (not a separate list merged in once at the very end) --
    # save_manifest() below gets called after every single pair, so a kill mid-run (e.g. the agent
    # session itself ending, which has happened) only ever loses the ONE pair in flight, not every
    # already-completed pair+generated-image from earlier in the same invocation.
    existing_by_key = {(r["object"], r["affordance"]): r for r in existing}

    def save_manifest():
        with open(manifest_path, "w") as f:
            json.dump(list(existing_by_key.values()), f, indent=2)

    manifest = []
    for obj in objects:
        try:
            img_path = resolve_image_path(obj)
        except FileNotFoundError as e:
            print(f"  {obj}: {e}")
            continue
        obj_out_dir = os.path.join(OUT_DIR, obj)
        os.makedirs(obj_out_dir, exist_ok=True)

        print(f"\n=== {obj} ===")
        for affordance, gloss in AFFORDANCE_VOCAB.items():
            out_path = os.path.join(obj_out_dir, f"{obj}_{affordance}.png")
            record = existing_by_key.get((obj, affordance), {})
            record.update({
                "object": obj, "affordance": affordance, "gloss": gloss, "model": IMAGE_MODEL,
                "quality": QUALITY, "source_image": img_path, "output_image": out_path,
            })

            is_pass = record.get("judge_verdict") == "pass"
            is_exhausted_fail = record.get("retry_exhausted") and not is_pass
            if not rejudge and (is_pass or (is_exhausted_fail and not retry_failed)):
                why = "PASS" if is_pass else "retries exhausted, still FAIL"
                print(f"  {affordance}: already resolved ({why}), skipping")
                manifest.append(record)
                continue  # already in existing_by_key unchanged -- nothing new to persist

            if do_judge:
                if retry_failed and is_exhausted_fail:
                    print(f"  {affordance}: re-attempting previously-exhausted FAIL (--retry-failed)")
                else:
                    print(f"  {affordance}:")
                record.update(
                    generate_and_judge(api_key, judge_client, obj, img_path, affordance, gloss, out_path)
                )
            else:
                prompt = PROMPT_TEMPLATE.format(affordance=affordance, gloss=gloss)
                png_bytes, err = edit_image(api_key, img_path, prompt)
                record["prompt"] = prompt
                if png_bytes is None:
                    print(f"  {affordance}: FAILED -- {err}")
                    record["status"], record["error"] = "failed", err
                else:
                    with open(out_path, "wb") as f:
                        f.write(png_bytes)
                    print(f"  {affordance}: saved {out_path}")
                    record["status"] = "ok"
                time.sleep(REQUEST_DELAY_S)

            existing_by_key[(obj, affordance)] = record
            save_manifest()
            manifest.append(record)

    print(f"\nSaved {manifest_path}")

    judged = [r for r in manifest if "judge_verdict" in r]
    if judged:
        n_pass = sum(r["judge_verdict"] == "pass" for r in judged)
        print(f"Judge: {n_pass}/{len(judged)} pass")
        for r in judged:
            if r["judge_verdict"] != "pass":
                n_att = len(r.get("attempts", [])) or 1
                print(f"  [{r['judge_verdict'].upper()}] {r['object']}/{r['affordance']} "
                      f"(after {n_att} attempt{'s' if n_att != 1 else ''}): {r['judge_reasoning']}")


if __name__ == "__main__":
    main()
